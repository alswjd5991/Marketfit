// 행사 카테고리 8종. 필터·행사 카드·상세·대시보드가 모두 이 분류 하나만 쓴다
// (원문 category는 공고마다 표현이 제각각이라 화면에 그대로 내보이지 않는다).
// 판매자 입장에서 "어떤 손님이 오는 자리인가"로 나눴다.
export type CategoryGroup =
  | "플리마켓"
  | "축제 부스"
  | "야시장"
  | "먹거리 부스"
  | "시즌마켓"
  | "박람회·전시"
  | "아트·디자인 마켓"
  | "대학 마켓";

export const CATEGORY_GROUPS: CategoryGroup[] = [
  "플리마켓",
  "축제 부스",
  "야시장",
  "먹거리 부스",
  "시즌마켓",
  "박람회·전시",
  "아트·디자인 마켓",
  "대학 마켓",
];

// 위에서부터 먼저 맞는 규칙을 쓴다 — 순서가 중요하다.
// 예: "목포 국가유산 야행 플리마켓"은 플리마켓보다 야시장, "서울디자인 마켓(축제 판매부스)"은 축제보다 디자인.
const RULES: [RegExp, CategoryGroup][] = [
  [/대학/, "대학 마켓"],
  [/야시장|야행|야시|나이트마켓|밤장/, "야시장"],
  [/먹거리|푸드트럭/, "먹거리 부스"],
  [/박람회|북페어|식품대전|전시/, "박람회·전시"],
  [/아트|디자인/, "아트·디자인 마켓"],
  [/시즌마켓|광화문|가을마켓|봄마켓|크리스마스/, "시즌마켓"],
  [/플리마켓 페스티벌/, "플리마켓"], // 플리마켓 자체가 행사인 경우(번개장터 등)
  [/축제|페스티벌|페스타|festa/i, "축제 부스"],
];

/** 원문 카테고리와 행사명을 함께 보고 8종 중 하나로 정한다. */
export function getCategoryGroup(category: string | null, name: string): CategoryGroup {
  const text = `${category ?? ""} ${name}`;
  return RULES.find(([re]) => re.test(text))?.[1] ?? "플리마켓";
}
